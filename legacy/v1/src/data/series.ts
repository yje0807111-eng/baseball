import type { BatPos, BatterCard, Franchise, PitchRole, PitcherCard, Series } from './types';

// ⚠️ 능력치 초안: 시즌 기록과 인지도를 바탕으로 한 추정치. 실제 기록으로 검증·보정 필요.

type Extra = { id?: string; note?: string };

const b = (
  name: string, pos: string,
  con: number, pow: number, eye: number, spd: number, def: number,
  extra: Extra = {},
): BatterCard => ({
  type: 'batter', id: extra.id ?? name, name, pos: pos.split('/') as BatPos[],
  con, pow, eye, spd, def, note: extra.note,
});

const p = (
  name: string, role: PitchRole,
  stu: number, ctl: number, sta: number,
  extra: Extra = {},
): PitcherCard => ({
  type: 'pitcher', id: extra.id ?? name, name, role, stu, ctl, sta, note: extra.note,
});

